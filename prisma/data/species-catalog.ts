/** Separa gênero e epíteto específico, ignorando o sinal de híbrido (×). */
export function splitScientificName(name: string): { genus: string | null; epithet: string | null } {
  const parts = name.split(/\s+/).filter((p) => p !== "×" && p !== "x");
  return { genus: parts[0] ?? null, epithet: parts[1] ?? null };
}

/** Linhas prontas para `prisma.species.createMany`. */
export function speciesCatalogData() {
  return SPECIES_CATALOG.map(([scientificName, popularName, family, origin, invasive, nativeRange, notes]) => ({
    scientificName,
    popularName,
    family,
    origin,
    invasive,
    nativeRange,
    notes: notes ?? null,
    ...splitScientificName(scientificName),
  }));
}
